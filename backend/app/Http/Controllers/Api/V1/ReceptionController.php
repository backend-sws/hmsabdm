<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Controllers\Controller;

use App\Http\Traits\HasApiResponse;
use App\Http\Traits\AbdmValidatable;
use App\Models\Patient;
use App\Services\Abdm\AbdmServiceInterface;
use App\Services\Reception\ReceptionServiceInterface;
use Illuminate\Http\Request;
use OpenApi\Attributes as OA;

#[OA\Tag(
    name: "4. Reception",
    description: "Flow C & D — Walk-in Registration, Departments, OPD Visit, Scan & Share Queue"
)]
class ReceptionController extends Controller
{
    use HasApiResponse, AbdmValidatable;

    public function __construct(
        protected AbdmServiceInterface $abdmService,
        protected ReceptionServiceInterface $receptionService
    ) {}


    #[OA\Get(
        path: "/api/v1/reception/scan-and-share/queues",
        summary: "List all patients waiting in queue from Scan & Share",
        description: "Fetches a list of patients who have scanned the hospital's QR code and are waiting to be registered. Supports patient search.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\Parameter(name: "search", in: "query", description: "Search by patient name, mobile, or token", required: false, schema: new OA\Schema(type: "string"))]
    #[OA\Parameter(name: "all", in: "query", description: "Set to true to fetch all queue records without pagination", required: false, schema: new OA\Schema(type: "boolean", example: false))]
    #[OA\Parameter(name: "per_page", in: "query", description: "Number of items per page (default: 15)", required: false, schema: new OA\Schema(type: "integer", example: 15))]
    #[OA\Parameter(name: "page", in: "query", description: "Page number", required: false, schema: new OA\Schema(type: "integer", example: 1))]
    #[OA\Response(response: 200, description: "List of waiting queues")]
    public function getWaitingQueues(Request $request)
    {
        $hospitalId = $this->getHospitalId($request);
        $queues = $this->receptionService->getWaitingQueues($hospitalId, $request);
        return $this->paginatedOrSuccessResponse($queues, 'List of waiting queues');
    }

    #[OA\Post(
        path: "/api/v1/reception/scan-and-share/token",
        summary: "Find patient in queue by token",
        description: "Searches the waiting queue using the specific token number generated by the patient's ABHA app.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\RequestBody(
        required: true,
        content: new OA\JsonContent(
            properties: [
                new OA\Property(property: "token", type: "string", example: "482")
            ]
        )
    )]
    #[OA\Response(response: 200, description: "Patient details")]
    public function getByToken(Request $request)
    {
        $request->validate(['token' => 'required|string']);
        $hospitalId = $this->getHospitalId($request);

        try {
            $queue = $this->receptionService->getQueueByToken($hospitalId, $request->token);
            return $this->successResponse($queue);
        } catch (\Exception $e) {
            return $this->errorResponse($e->getMessage(), null, 404);
        }
    }

    #[OA\Get(
        path: "/api/v1/reception/departments",
        summary: "Get all departments with active doctors",
        description: "Used in the reception dropdowns to select a department and doctor for assigning an OPD visit. Returns all active records by default for easy dropdown selection.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\Parameter(name: "search", in: "query", description: "Search by department name or code", required: false, schema: new OA\Schema(type: "string"))]
    #[OA\Parameter(name: "all", in: "query", description: "Set to true to fetch all departments without pagination", required: false, schema: new OA\Schema(type: "boolean", example: true))]
    #[OA\Parameter(name: "per_page", in: "query", description: "Number of items per page (if paginating)", required: false, schema: new OA\Schema(type: "integer"))]
    #[OA\Parameter(name: "page", in: "query", description: "Page number", required: false, schema: new OA\Schema(type: "integer"))]
    #[OA\Response(response: 200, description: "Departments and doctors list")]
    public function getDepartments(Request $request)
    {
        $hospitalId = $this->getHospitalId($request);
        $departments = $this->receptionService->getDepartmentsWithDoctors($hospitalId, $request);
        return $this->paginatedOrSuccessResponse($departments, 'Departments and doctors list');
    }

    #[OA\Post(
        path: "/api/v1/reception/register",
        summary: "Manual Patient Registration (Without ABHA)",
        description: "Registers a walk-in patient who does not have an ABHA card or chooses manual registration.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\RequestBody(
        required: true,
        content: new OA\JsonContent(
            required: ["name"],
            properties: [
                new OA\Property(property: "name", type: "string", example: "Jane Doe"),
                new OA\Property(property: "guardian_name", type: "string", example: "Robert Doe", description: "Father / Mother / Spouse Name"),
                new OA\Property(property: "guardian_relation", type: "string", example: "Father"),
                new OA\Property(property: "guardian_phone", type: "string", example: "9876500000"),
                new OA\Property(property: "id_proof_type", type: "string", enum: ["aadhaar", "pan", "voter_id", "driving_license", "passport", "ration_card", "other"], example: "driving_license"),
                new OA\Property(property: "id_proof_number", type: "string", example: "DL1420110012345"),
                new OA\Property(property: "mobile", type: "string", example: "9876543210"),
                new OA\Property(property: "gender", type: "string", example: "F"),
                new OA\Property(property: "dob", type: "string", format: "date", example: "1995-08-15"),
                new OA\Property(property: "blood_group", type: "string", example: "B+"),
                new OA\Property(property: "address", type: "string", example: "45 Park Street"),
                new OA\Property(property: "city", type: "string", example: "Mumbai"),
                new OA\Property(property: "district", type: "string", example: "Mumbai Suburban"),
                new OA\Property(property: "state", type: "string", example: "Maharashtra"),
                new OA\Property(property: "pincode", type: "string", example: "400001"),
                new OA\Property(property: "custom_fields", type: "object", example: ["marital_status" => "Single", "occupation" => "Engineer"])
            ]
        )
    )]
    #[OA\Response(response: 201, description: "Patient Registered")]
    public function registerWithoutAbha(Request $request)
    {
        $validated = $request->validate([
            'name'              => 'required|string',
            'guardian_name'     => 'nullable|string|max:255',
            'guardian_relation' => 'nullable|string|max:50',
            'guardian_phone'    => 'nullable|string|max:20',
            'id_proof_type'     => 'nullable|string|in:aadhaar,pan,voter_id,driving_license,passport,ration_card,other',
            'id_proof_number'   => 'nullable|string|max:100',
            'mobile'            => 'nullable|string|max:15',
            'gender'            => 'nullable|string|size:1',
            'dob'               => 'nullable|date',
            'blood_group'       => 'nullable|string|max:5',
            'address'           => 'nullable|string',
            'city'              => 'nullable|string|max:100',
            'district'          => 'nullable|string|max:100',
            'state'             => 'nullable|string|max:100',
            'pincode'           => 'nullable|string|max:20',
            'photo'             => 'nullable|string',
            'kyc_verified'      => 'nullable|boolean',
            'custom_fields'     => 'nullable|array',
        ]);

        $hospitalId = $this->getHospitalId($request);
        $patient = $this->receptionService->registerPatient($hospitalId, $validated);
        
        return $this->createdResponse($patient, 'Patient registered successfully');
    }

    #[OA\Post(
        path: "/api/v1/reception/scan-and-share/confirm",
        summary: "Confirm a Scan & Share queue and generate OPD Visit",
        description: "Links the queued patient to a department and doctor, creating their final OPD appointment.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\RequestBody(
        required: true,
        content: new OA\JsonContent(
            properties: [
                new OA\Property(property: "queue_id", type: "integer"),
                new OA\Property(property: "doctor_id", type: "integer"),
                new OA\Property(property: "department_id", type: "integer"),
                new OA\Property(property: "appointment_type_id", type: "integer", nullable: true)
            ]
        )
    )]
    #[OA\Response(response: 200, description: "Queue Confirmed & OPD Visit Created")]
    public function confirmQueue(Request $request)
    {
        $request->validate([
            'queue_id' => 'required|integer|exists:counter_queues,id',
            'doctor_id' => 'required|integer|exists:doctors,id',
            'department_id' => 'required|integer|exists:departments,id',
            'appointment_type_id' => 'nullable|integer|exists:appointment_types,id',
        ]);

        $hospitalId = $this->getHospitalId($request);

        try {
            $visit = $this->receptionService->confirmQueue(
                $hospitalId,
                $request->queue_id,
                $request->doctor_id,
                $request->department_id,
                $request->appointment_type_id
            );

            return $this->successResponse($visit, 'Queue Confirmed and OPD Visit Created');
        } catch (\Exception $e) {
            return $this->errorResponse($e->getMessage(), null, 400);
        }
    }

    #[OA\Post(
        path: "/api/v1/reception/visit",
        summary: "Create OPD visit (Parcha) with Split / Multi-Mode Payment support",
        description: "Creates an OPD registration slip (visit) with multi-mode payment, split payments, and fee discounts.",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\RequestBody(
        required: true,
        content: new OA\JsonContent(
            properties: [
                new OA\Property(property: "patient_id", type: "integer", example: 10),
                new OA\Property(property: "doctor_id", type: "integer", example: 5),
                new OA\Property(property: "department_id", type: "integer", example: 2),
                new OA\Property(property: "appointment_type_id", type: "integer", nullable: true, example: 1),
                new OA\Property(property: "chief_complaint", type: "string", example: "Fever and headache"),
                new OA\Property(property: "fee_charged", type: "number", format: "float", example: 500.00),
                new OA\Property(property: "discount", type: "number", format: "float", example: 50.00),
                new OA\Property(property: "amount_paid", type: "number", format: "float", example: 450.00),
                new OA\Property(property: "payment_status", type: "string", enum: ["pending", "paid", "partial", "waived"], example: "paid"),
                new OA\Property(property: "payment_method", type: "string", enum: ["cash", "card", "upi", "insurance", "split", "cheque", "other"], example: "split"),
                new OA\Property(property: "payment_ref", type: "string", example: "REF12345"),
                new OA\Property(
                    property: "payment_breakdown",
                    type: "array",
                    items: new OA\Items(
                        properties: [
                            new OA\Property(property: "method", type: "string", example: "cash"),
                            new OA\Property(property: "amount", type: "number", example: 250.00),
                            new OA\Property(property: "ref", type: "string", example: null)
                        ]
                    ),
                    example: [
                        ["method" => "cash", "amount" => 250.00],
                        ["method" => "upi", "amount" => 200.00, "ref" => "UPI987654321"]
                    ]
                )
            ]
        )
    )]
    #[OA\Response(response: 200, description: "OPD Visit Created")]
    public function createVisit(Request $request)
    {
        $validated = $request->validate([
            'patient_id'          => 'required|integer|exists:patients,id',
            'doctor_id'           => 'required|integer|exists:doctors,id',
            'department_id'       => 'required|integer|exists:departments,id',
            'appointment_type_id' => 'nullable|integer|exists:appointment_types,id',
            'chief_complaint'     => 'nullable|string',
            'fee_charged'         => 'nullable|numeric|min:0',
            'discount'            => 'nullable|numeric|min:0',
            'amount_paid'         => 'nullable|numeric|min:0',
            'payment_status'      => 'nullable|string|in:pending,paid,partial,waived',
            'payment_method'      => 'nullable|string|in:cash,card,upi,insurance,split,cheque,other',
            'payment_ref'         => 'nullable|string|max:255',
            'payment_breakdown'   => 'nullable|array',
            'payment_breakdown.*.method' => 'required_with:payment_breakdown|string',
            'payment_breakdown.*.amount' => 'required_with:payment_breakdown|numeric|min:0.01',
            'payment_breakdown.*.ref'    => 'nullable|string',
        ]);

        $hospitalId = $this->getHospitalId($request);

        try {
            $visit = $this->receptionService->createOpdVisit($hospitalId, $validated);
            return $this->successResponse($visit, 'OPD Visit Created Successfully');
        } catch (\Exception $e) {
            return $this->errorResponse($e->getMessage(), null, 400);
        }
    }

    #[OA\Post(
        path: "/api/v1/reception/quick-visit",
        summary: "1-Click Quick Re-visit Token for Existing Patients",
        description: "Issues an instant OPD appointment token for an existing patient without re-entering demographics. Checks hospital free follow-up validity rules (e.g. 7 days).",
        security: [["bearerAuth" => []]],
        tags: ["4. Reception"]
    )]
    #[OA\RequestBody(
        required: true,
        content: new OA\JsonContent(
            required: ["doctor_id"],
            properties: [
                new OA\Property(property: "patient_id", type: "integer", nullable: true, example: 10),
                new OA\Property(property: "uhid", type: "string", nullable: true, example: "UHID-2026-0001"),
                new OA\Property(property: "mobile", type: "string", nullable: true, example: "9876543210"),
                new OA\Property(property: "doctor_id", type: "integer", example: 5),
                new OA\Property(property: "department_id", type: "integer", nullable: true, example: 2),
                new OA\Property(property: "appointment_type_id", type: "integer", nullable: true, example: 1),
                new OA\Property(property: "chief_complaint", type: "string", nullable: true, example: "Follow-up check"),
                new OA\Property(property: "fee_charged", type: "number", format: "float", nullable: true, example: 500.00),
                new OA\Property(property: "discount", type: "number", format: "float", nullable: true, example: 0.00),
                new OA\Property(property: "amount_paid", type: "number", format: "float", nullable: true, example: 500.00),
                new OA\Property(property: "payment_status", type: "string", nullable: true, enum: ["pending", "paid", "partial", "waived"]),
                new OA\Property(property: "payment_method", type: "string", nullable: true, enum: ["cash", "card", "upi", "insurance", "split", "cheque", "other"]),
                new OA\Property(property: "notes", type: "string", nullable: true)
            ]
        )
    )]
    #[OA\Response(response: 200, description: "Quick Re-visit Token Generated")]
    #[OA\Response(response: 400, description: "Error generating token or patient not found")]
    public function quickVisit(Request $request)
    {
        $validated = $request->validate([
            'patient_id'          => 'nullable|integer|exists:patients,id',
            'uhid'                => 'nullable|string',
            'mobile'              => 'nullable|string',
            'doctor_id'           => 'required|integer|exists:doctors,id',
            'department_id'       => 'nullable|integer|exists:departments,id',
            'appointment_type_id' => 'nullable|integer|exists:appointment_types,id',
            'chief_complaint'     => 'nullable|string',
            'notes'               => 'nullable|string',
            'fee_charged'         => 'nullable|numeric|min:0',
            'discount'            => 'nullable|numeric|min:0',
            'amount_paid'         => 'nullable|numeric|min:0',
            'payment_status'      => 'nullable|string|in:pending,paid,partial,waived',
            'payment_method'      => 'nullable|string|in:cash,card,upi,insurance,split,cheque,other',
            'payment_ref'         => 'nullable|string|max:255',
            'payment_breakdown'   => 'nullable|array',
        ]);

        if (empty($validated['patient_id']) && empty($validated['uhid']) && empty($validated['mobile'])) {
            return $this->errorResponse('Please provide at least one of: patient_id, uhid, or mobile number.', null, 422);
        }

        $hospitalId = $this->getHospitalId($request);

        try {
            $result = $this->receptionService->quickRevisit($hospitalId, $validated);
            if (!empty($result['requires_selection'])) {
                return $this->successResponse($result, 'Multiple patient records matched. Selection required.');
            }
            return $this->successResponse($result, 'Quick Re-visit Token Generated Successfully');
        } catch (\Exception $e) {
            return $this->errorResponse($e->getMessage(), null, 400);
        }
    }
}

